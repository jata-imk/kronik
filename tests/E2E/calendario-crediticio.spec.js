import { expect, test } from "@playwright/test";
import { failOnConsoleErrors, login } from "./support/auth.js";

test("publica la plantilla y compara vencimientos con teclado y en móvil", async ({ page }, testInfo) => {
    const revisarConsola = await failOnConsoleErrors(page);
    await login(page);
    await page.goto("/productos-crediticios/calendario");
    await expect(page.getByRole("heading", { name: "Calendario crediticio", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Nuevo borrador" }).click();
    await page.getByRole("button", { name: "Cargar plantilla CNBV 2026" }).click();
    await page.getByLabel("Cobertura hasta").fill("2026-02-30");
    await page.getByLabel("Cobertura hasta").press("Enter");
    await expect(page.getByText(/fin de cobertura.*ser una fecha válida/)).toBeVisible();
    await expect(page.getByLabel("Cobertura hasta")).toBeFocused();
    await expect(page.getByLabel("Cobertura hasta")).toHaveValue("2026-02-30");
    await page.getByLabel("Cobertura hasta").fill("2027-01-01");
    const editor = page.getByRole("dialog", { name: "Nuevo borrador" });
    const fechas = editor.getByRole("textbox", { name: "Fecha", exact: true });
    await fechas.first().fill("2026-02-30");
    await fechas.nth(1).fill("");
    await editor.getByRole("button", { name: "Guardar borrador" }).click();
    await expect(editor.getByText(/fecha del feriado.*ser una fecha válida/)).toBeVisible();
    await editor.getByRole("button", { name: "Quitar fecha" }).first().click();
    await expect(editor.getByText(/fecha del feriado.*ser una fecha válida/)).toHaveCount(0);
    await expect(editor.getByText(/fecha del feriado es obligatorio/)).toBeVisible();
    await expect(fechas.first()).toHaveAttribute("aria-invalid", "true");
    await editor.getByRole("button", { name: "Cargar plantilla CNBV 2026" }).click();
    await expect(editor.getByText(/fecha del feriado es obligatorio/)).toHaveCount(0);
    const fechaOriginal = await fechas.nth(1).inputValue();
    const fechaRepetida = `${await fechas.first().inputValue()} `;
    await fechas.nth(1).fill(fechaRepetida);
    await editor.getByRole("button", { name: "Guardar borrador" }).click();
    await expect(editor.getByText(/Hay fechas repetidas en feriados/)).toBeVisible();
    await expect(fechas.nth(1)).toHaveAttribute("aria-invalid", "true");
    await fechas.nth(1).fill(fechaOriginal);
    await expect(editor.getByText(/Hay fechas repetidas en feriados/)).toHaveCount(0);
    await fechas.nth(1).fill(fechaRepetida);
    await editor.getByRole("button", { name: "Guardar borrador" }).click();
    await expect(editor.getByText(/Hay fechas repetidas en feriados/)).toBeVisible();
    await editor.getByRole("button", { name: "Quitar fecha" }).first().click();
    await expect(editor.getByText(/Hay fechas repetidas en feriados/)).toHaveCount(0);
    await editor.getByRole("button", { name: "Cargar plantilla CNBV 2026" }).click();
    await page.getByLabel("Cobertura hasta").fill("2027-01-01");
    await page.getByLabel("Cobertura hasta").press("Tab");
    page.once("dialog", aviso => aviso.dismiss());
    await page.getByRole("dialog", { name: "Nuevo borrador" }).getByRole("button", { name: /^(Cerrar|Close)$/i }).click();
    await expect(page.getByLabel("Cobertura hasta")).toHaveValue("2027-01-01");
    await page.getByRole("button", { name: "Guardar borrador" }).click();
    await expect(page).toHaveURL(/calendario\/\d+$/);
    await page.getByRole("button", { name: "Publicar", exact: true }).click();
    await page.getByRole("button", { name: "Publicar versión" }).click();
    await expect(page.getByText("Vigente", { exact: true }).first()).toBeVisible();
    await expect(page.getByText(/Cobertura revisada.*2027-01-01/)).toBeVisible();
    await page.getByRole("tab", { name: "Ejemplos" }).focus();
    await page.keyboard.press("Enter");
    await page.getByRole("button", { name: "Calcular ejemplo" }).click();
    await expect(page.getByRole("button", { name: /2026-11-14 → 2026-11-17/ })).toBeVisible();
    await expect(page.getByText("2026-11-21", { exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("calendario-ejemplo-claro.png"), fullPage: true });

    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("tab", { name: "Calendario", exact: true }).click();
    await page.getByRole("button", { name: "Cambiar tema", exact: true }).click();
    await expect(page.locator("html")).toHaveClass(/app-dark/);
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
    await page.screenshot({ path: testInfo.outputPath("calendario-movil-oscuro.png"), fullPage: true });
    revisarConsola();
});
