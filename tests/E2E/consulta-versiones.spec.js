import { expect, test } from "@playwright/test";
import { login, failOnConsoleErrors } from "./support/auth.js";

test("plantilla activa y retirada abren el editor exacto sin mutaciones", async ({ page }, testInfo) => {
    test.setTimeout(90_000);
    const noErrors = await failOnConsoleErrors(page);
    await login(page);
    await page.goto("/plantillas-documentos");
    await page.getByRole("button", { name: "Nueva plantilla", exact: true }).click();
    await page.getByLabel("Nombre *", { exact: true }).fill("Consulta histórica documental");
    await page.locator(".ql-editor:visible").fill("Contenido histórico uno {{cliente.nombre_completo}}.");
    await page.getByLabel("Marca de agua (opcional)").fill("VERSIÓN UNO");
    await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
    await expect(page.locator("#template-editor")).toHaveCount(0);
    await page.getByLabel("Buscar plantillas").fill("Consulta histórica documental");
    await page.getByRole("button", { name: /Consulta histórica documental/ }).click();
    await page.getByRole("button", { name: "Activar versión", exact: true }).click();
    await page.getByRole("button", { name: "Activar", exact: true }).click();
    await expect(page.getByText("Versión activada", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Ver versión", exact: true }).click();
    const dialog = page.locator("#template-editor");
    await expect(dialog).toContainText("Consultar versión 1");
    await expect(dialog.locator(".ql-editor:visible")).toContainText("Contenido histórico uno");
    await expect(dialog.locator(".ql-editor:visible")).toHaveAttribute("contenteditable", "false");
    await expect(dialog.getByRole("button", { name: "Guardar borrador" })).toHaveCount(0);
    await expect(dialog.getByRole("button", { name: "Imagen", exact: true })).toHaveCount(0);
    await dialog.getByLabel("Buscar variables").fill("cliente");
    await expect(dialog.getByLabel("Buscar variables")).toHaveValue("cliente");
    const writes = [];
    page.on("request", req => { if (["POST", "PUT", "PATCH", "DELETE"].includes(req.method())) writes.push(req.url()); });
    await dialog.locator("#template-name").press("Enter");
    await dialog.getByRole("button", { name: "Encabezado", exact: true }).click();
    await dialog.getByRole("button", { name: "Pie de página", exact: true }).click();
    await dialog.getByRole("button", { name: "Contenido", exact: true }).click();
    expect(writes).toEqual([]);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: testInfo.outputPath("plantilla-consulta-movil.png"), fullPage: true });
    await dialog.getByRole("button", { name: "Cerrar consulta" }).click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole("button", { name: "Retirar versión", exact: true }).click();
    await page.getByRole("button", { name: "Retirar", exact: true }).click();
    await expect(page.getByText("Versión retirada", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Ver versión", exact: true }).click();
    await expect(dialog).toContainText("Consultar versión 1");
    await expect(dialog.locator("#watermark")).toHaveValue("VERSIÓN UNO");
    noErrors();
});


test("originación distingue números y conserva políticas históricas en consulta", async ({page}, testInfo) => {
    await login(page);
    await page.goto("/productos-crediticios");
    await page.getByRole("link", {name:"Consultar política",exact:true}).first().click();
    await page.getByRole("button", {name:"Crear política",exact:true}).click();
    await page.getByLabel("Separación de funciones", {exact:true}).click();
    await page.getByRole("option", {name:"Dual: quien capturó no aprueba",exact:true}).click();
    await page.getByLabel("Requisito SIC", {exact:true}).click();
    await page.getByRole("option", {name:"Evaluación manual documentada permitida",exact:true}).click();
    await page.locator("#pol-maximo").pressSequentially("10000");
    await page.locator("#pol-vigencia").fill("30");
    await page.locator("fieldset").filter({hasText:"Documentos requeridos por esta política"}).getByRole("checkbox").first().check();
    await page.locator("#pol-capacidad").fill("Evaluar evidencias de ingresos y egresos conforme al procedimiento interno de QA.");
    await page.locator("#pol-validacion").fill("Acta interna QA de criterios para pruebas, sin operación real.");
    await page.locator("#pol-confirmacion").check();
    await page.getByRole("button",{name:"Guardar nueva versión de política",exact:true}).click();
    await expect(page.getByText("Consulta · política 1 · versión de producto 1.",{exact:true})).toBeVisible();
    await page.getByRole("button",{name:"Nueva versión de política",exact:true}).click();
    await page.locator("#pol-vigencia").fill("31");
    await page.locator("#pol-validacion").fill("Acta interna QA segunda revisión de criterios de prueba.");
    await page.locator("#pol-confirmacion").check();
    await page.getByRole("button",{name:"Guardar nueva versión de política",exact:true}).click();
    await expect(page.getByText("Política actual: versión 2.",{exact:true})).toBeVisible();
    await page.getByRole("button",{name:"Consultar política 1",exact:true}).click();
    await expect(page.locator("#pol-vigencia")).toHaveValue("30");
    await expect(page.locator("#pol-vigencia")).toHaveAttribute("readonly","");
    const writes=[];page.on("request",req=>{if(["POST","PUT","PATCH","DELETE"].includes(req.method()))writes.push(req.url());});
    await page.locator("#pol-vigencia").press("Enter");
    await expect(page.getByRole("button",{name:"Guardar nueva versión de política"})).toHaveCount(0);
    expect(writes).toEqual([]);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:testInfo.outputPath("politica-historica-movil.png"),fullPage:true});
});
