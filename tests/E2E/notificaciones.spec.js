import { test, expect } from "@playwright/test";
import { failOnConsoleErrors, login } from "./support/auth.js";
import { createNotification } from "./support/notifications.js";

test("SMS conserva texto y versiones exactas sin PDF, también en móvil y teclado", async ({ page }, testInfo) => {
    const assertConsole = await failOnConsoleErrors(page);
    const pdfRequests = [];
    page.on("request", request => { if (request.url().includes("previsualizar-pdf")) pdfRequests.push(request.url()); });
    await login(page);
    await page.goto("/comunicaciones/notificaciones");
    await page.getByRole("button", { name: "Nueva plantilla", exact: true }).click();
    await page.getByLabel("Nombre", { exact: true }).fill("SMS institucional QA");
    await page.getByLabel("Clave", { exact: true }).fill("sms-i3-" + Date.now());
    const content = page.getByLabel("Contenido", { exact: true });
    await content.fill("Hola ");
    await content.press("End");
    await page.getByLabel("Buscar variables").fill("Primer nombre");
    await page.getByRole("button", { name: /Primer nombre/ }).click();
    await expect(content).toHaveValue("Hola {nombre}");
    await content.fill("Hola {nombre}, á &amp; <b>literal</b>.");
    await page.getByRole("button", { name: "Actualizar previsualización" }).click();
    await expect(page.getByTestId("text-preview")).toHaveText("Hola María, á &amp; <b>literal</b>.");
    await expect(page.getByText(/Estimación:/)).toBeVisible();
    await content.fill("Hola {no_permitida}.");
    await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
    await expect(page.getByText(/La plantilla contiene una variable no permitida/)).toBeVisible();
    await expect(content).toHaveValue("Hola {no_permitida}.");
    await content.fill("Hola {nombre}, á &amp; <b>literal</b>.");
    await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
    await expect(page.getByRole("heading", { name: /Consultar versión 1/ })).toBeVisible();
    page.once("dialog", dialog => dialog.accept());
    await page.getByRole("button", { name: "Activar versión", exact: true }).click();
    await expect(page.getByRole("heading", { name: /Consultar versión 1 · Activa/ })).toBeVisible();
    await expect(content).toHaveAttribute("readonly", "");
    await expect(page.getByRole("button", { name: "Guardar borrador" })).toHaveCount(0);
    await content.press("Enter");
    await expect(content).toHaveValue("Hola {nombre}, á &amp; <b>literal</b>.");
    page.once("dialog", dialog => dialog.accept());
    await page.getByRole("button", { name: "Nueva versión", exact: true }).click();
    await expect(page.getByRole("heading", { name: /Editar versión 2/ })).toBeVisible();
    await content.fill("Otra redacción para {nombre}.");
    await page.getByRole("button", { name: "Actualizar previsualización" }).click();
    await expect(page.getByTestId("text-preview")).toHaveText("Otra redacción para María.");
    await page.getByRole("button", { name: /^V1 · Activa/ }).click();
    await expect(page.getByRole("heading", { name: /Consultar versión 1 · Activa/ })).toBeVisible();
    await page.getByRole("button", { name: "Actualizar previsualización" }).click();
    await expect(page.getByTestId("text-preview")).toHaveText("Hola María, á &amp; <b>literal</b>.");
    await page.setViewportSize({ width: 390, height: 844 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: "test-results/notificaciones-mobile.png", fullPage: true });
    await testInfo.attach("notificaciones-mobile", { path: "test-results/notificaciones-mobile.png", contentType: "image/png" });
    expect(pdfRequests).toEqual([]);
    assertConsole();
});

test("correo HTML y documentos muestran HTML continuo sin solicitar PDF", async ({ page }) => {
    const assertConsole = await failOnConsoleErrors(page, { sandboxedHtml: true });
    let pdf = 0;
    page.on("request", request => { if (request.url().includes("previsualizar-pdf")) pdf++; });
    await login(page);
    await createNotification(page, { key: "correo-i3-" + Date.now(), channel: "email", format: "html", body: "Hola {nombre}, correo institucional." });
    await page.getByRole("button", { name: "Actualizar previsualización" }).click();
    const frame = page.frameLocator('iframe[title="Previsualización HTML"]');
    await expect(frame.locator("article")).toContainText("Hola María, correo institucional.");
    await expect(frame.locator("script")).toHaveCount(0);
    await expect(page.locator('iframe[title="Previsualización HTML"]')).toHaveAttribute("sandbox", "");
    await expect(page.getByRole("button", { name: "Imagen", exact: true })).toHaveCount(0);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: "test-results/notificaciones-desktop.png", fullPage: true });
    await page.goto("/plantillas-documentos");
    await page.getByRole("button", { name: "Nueva plantilla", exact: true }).click();
    await page.getByLabel("Nombre *").fill("HTML documental I3");
    await page.locator(".ql-editor:visible").fill("Documento sin guardar para {{cliente.nombre_completo}}.");
    await page.getByRole("button", { name: "Actualizar previsualización" }).click();
    await expect(frame.locator("article")).toContainText("Documento sin guardar para María Ejemplo López.");
    await expect(page.getByRole("button", { name: "Previsualizar PDF de los cambios" })).toBeVisible();
    expect(pdf).toBe(0);
    assertConsole();
});
