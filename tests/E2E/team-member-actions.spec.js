import { expect, test } from "@playwright/test";
import { failOnConsoleErrors, login } from "./support/auth.js";

test("administra usuarios desde el equipo y conserva el contexto", async ({ page }, testInfo) => {
    test.setTimeout(90_000);
    await login(page);
    const assertNoConsoleErrors = await failOnConsoleErrors(page);
    await page.goto("/admin/teams");
    await page.getByRole("link", { name: /abrir configuración de test user's team/i }).click();
    const teamUrl = page.url();
    await page.getByRole("button", { name: "Editar Integrante acciones E2E", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await expect(dialog).toContainText("Operaciones E2E");
    await dialog.getByLabel("Nombre", { exact: true }).fill("Integrante editado E2E");
    await dialog.getByRole("button", { name: "Guardar", exact: true }).click();
    await expect(dialog).toBeHidden();
    await expect(page).toHaveURL(teamUrl);
    await page.getByRole("button", { name: "Reenviar invitación a Pendiente de equipo E2E", exact: true }).click();
    await expect(page.getByText("Invitación reenviada", { exact: true })).toBeVisible();
    await expect(page).toHaveURL(teamUrl);
    await page.getByRole("button", { name: "Desactivar cuenta de Integrante editado E2E", exact: true }).click();
    await expect(page.getByRole("alertdialog")).toContainText("todos los equipos");
    await page.getByRole("button", { name: "Desactivar cuenta", exact: true }).click();
    await expect(page.getByRole("button", { name: "Reactivar cuenta de Integrante editado E2E", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Reactivar cuenta de Integrante editado E2E", exact: true }).click();
    await page.getByRole("button", { name: "Reactivar cuenta", exact: true }).click();
    await expect(page.getByRole("button", { name: "Desactivar cuenta de Integrante editado E2E", exact: true })).toBeVisible();
    await expect(page).toHaveURL(teamUrl);
    await page.getByRole("button", { name: "Invitar usuario", exact: true }).click();
    await dialog.getByLabel("Nombre", { exact: true }).fill("Nueva integrante E2E");
    await dialog.getByLabel("Correo electrónico", { exact: true }).fill("nueva.integrante@example.test");
    await dialog.getByRole("button", { name: "Guardar", exact: true }).click();
    await expect(dialog).toBeHidden();
    await expect(page.getByText("Nueva integrante E2E", { exact: true })).toBeVisible();
    await expect(page).toHaveURL(teamUrl);
    await page.goto("/admin/teams");
    await page.getByRole("link", { name: "Abrir configuración de Operaciones E2E", exact: true }).click();
    const operationsUrl = page.url();
    await page.getByRole("button", { name: "Quitar a Integrante editado E2E del equipo", exact: true }).click();
    await expect(page.getByRole("alertdialog")).toContainText("Su cuenta y los demás equipos se conservan");
    await page.getByRole("button", { name: "Quitar del equipo", exact: true }).click();
    await expect(page.getByRole("button", { name: "Editar Integrante editado E2E", exact: true })).toHaveCount(0);
    await expect(page).toHaveURL(operationsUrl);
    await page.goto(teamUrl);
    await expect(page.getByRole("button", { name: "Editar Integrante editado E2E", exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("integrantes-acciones-desktop.png"), animations: "disabled" });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "Editar Integrante editado E2E", exact: true }).click();
    await page.screenshot({ path: testInfo.outputPath("integrante-formulario-mobile.png"), animations: "disabled" });
    assertNoConsoleErrors();
});
