import { expect, test } from "@playwright/test";
import { login } from "./support/auth.js";

test("prepara Bullet versionado y consulta sus bases en escritorio y móvil", async ({ page }, testInfo) => {
    await login(page);
    await page.goto("/productos-crediticios");
    await page.getByRole("button", { name: "Nuevo producto", exact: true }).click();
    const dialog = page.locator("#product-editor");
    await page.getByRole("textbox", { name: "Clave *", exact: true }).fill("BULLET-E2E");
    await page.getByLabel("Nombre comercial").fill("Bullet condiciones QA");
    await dialog.getByRole("tab", { name: "Montos y tasas", exact: true }).click();
    await dialog.getByRole("combobox", { name: "Intereses durante la mora", exact: true }).click();
    await page.getByRole("option", { name: "Moratorio sustituye al ordinario", exact: true }).click();
    await dialog.getByRole("tab", { name: "Reglas", exact: true }).click();
    await dialog.getByRole("checkbox", { name: /^Bullet/ }).check();
    await expect(dialog).toContainText("El capital vence al final");
    await dialog.getByRole("combobox", { name: "Pago de intereses Bullet", exact: true }).click();
    await page.getByRole("option", { name: "Intereses al vencimiento", exact: true }).click();
    await dialog.getByRole("combobox", { name: "Base moratoria", exact: true }).click();
    await page.getByRole("option", { name: "Obligación vencida impagada", exact: true }).click();
    await page.screenshot({ path: testInfo.outputPath("bullet-editor-desktop.png"), fullPage: true });
    await dialog.getByRole("button", { name: "Guardar borrador" }).click();
    await expect(dialog).toHaveCount(0);
    await page.getByRole("button").filter({ hasText: "Bullet condiciones QA" }).click();
    await expect(page.getByRole("button", { name: "Simular versión 1", exact: true })).toBeEnabled();
    await expect(page.getByRole("button", { name: "Simular", exact: true })).toBeEnabled();
    await page.getByRole("button", { name: "Ver versión 1", exact: true }).click();
    await dialog.getByRole("tab", { name: "Reglas", exact: true }).click();
    await expect(dialog).toContainText("Intereses al vencimiento");
    await expect(dialog).toContainText("Obligación vencida impagada");
    await expect(dialog).toContainText("Saldo insoluto");
    const writes = [];
    page.on("request", request => { if (["POST", "PUT", "PATCH", "DELETE"].includes(request.method())) writes.push(request.url()); });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(dialog.getByRole("button", { name: "Guardar borrador" })).toHaveCount(0);
    await expect(dialog.getByRole("combobox", { name: "Base moratoria" })).toHaveCount(0);
    await expect(dialog.getByRole("button", { name: "Usar base ordinaria para mora" })).toHaveCount(0);
    await expect(dialog.getByRole("textbox", { name: "Aplicación del prepago", exact: true })).toHaveValue("Conservar vencimiento");
    await dialog.getByText("Base moratoria", { exact: true }).scrollIntoViewIfNeeded();
    await expect(dialog.getByText("Obligación vencida impagada", { exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("bullet-consulta-movil.png"), fullPage: true });
    expect(writes).toEqual([]);
});
