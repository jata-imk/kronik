import { expect, test } from "@playwright/test";
import { failOnConsoleErrors, login } from "./support/auth.js";

test("administra el equipo seleccionado sin cambiar el actual y transfiere su responsable", async ({ page }, testInfo) => {
    test.setTimeout(90_000);
    await login(page);
    const assertNoConsoleErrors = await failOnConsoleErrors(page);
    await page.goto("/admin/teams");
    await page.getByRole("link", { name: "Abrir configuración de Operaciones E2E", exact: true }).click();
    const teamUrl = page.url();
    const teamId = teamUrl.split("/").at(-1);
    await expect(page.getByText("Cuenta · Equipo seleccionado", { exact: true })).toBeVisible();
    await expect(page.getByText("Invitaciones pendientes", { exact: true })).toBeVisible();
    await page.getByRole("link", { name: "Administrar roles", exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`team=${teamId}`));
    await expect(page.getByText("Configura los permisos de Operaciones E2E. El equipo actual no cambia.", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Crear rol", exact: true }).click();
    await page.getByRole("dialog").getByLabel("Nombre del Rol", { exact: true }).fill("Rol de operaciones E2E");
    await page.getByRole("dialog").getByRole("button", { name: "Crear", exact: true }).click();
    await expect(page.getByRole("dialog")).toBeHidden();
    await page.getByRole("link", { name: "Volver", exact: true }).click();
    await expect(page).toHaveURL(teamUrl);
    await page.getByLabel("Nuevo responsable", { exact: true }).click();
    await page.getByRole("option", { name: "Responsable E2E", exact: true }).click();
    await page.getByRole("button", { name: "Transferir responsable", exact: true }).click();
    await page.getByRole("button", { name: "Transferir", exact: true }).click();
    await expect(page.getByRole("row").filter({ hasText: "responsable.e2e@example.test" }).locator('[aria-label="Responsable del equipo"]')).toBeVisible();
    await page.getByRole("link", { name: "Ver bitácora del equipo", exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`team_id=${teamId}`));
    await expect(page.getByText("Actividad del equipo Operaciones E2E", { exact: true })).toBeVisible();
    await expect(page.getByRole("row").filter({ hasText: "Responsable transferido del usuario" })).toBeVisible();
    await page.getByRole("link", { name: "Volver", exact: true }).click();
    await page.getByRole("button", { name: "Desactivar equipo", exact: true }).click();
    await page.getByRole("button", { name: "Confirmar", exact: true }).click();
    await expect(page.getByRole("button", { name: "Reactivar equipo", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Reactivar equipo", exact: true }).click();
    await page.getByRole("button", { name: "Confirmar", exact: true }).click();
    await expect(page.getByRole("button", { name: "Desactivar equipo", exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("equipo-seleccionado-desktop.png"), animations: "disabled" });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: testInfo.outputPath("equipo-seleccionado-mobile.png"), animations: "disabled" });
    assertNoConsoleErrors();
});
