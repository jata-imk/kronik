import { flushPromises, shallowMount } from "@vue/test-utils";
import { useForm } from "@inertiajs/vue3";
import { expect, it, vi } from "vitest";
import RolePanel from "./RolePanel.vue";
const get = vi.hoisted(() => vi.fn());
vi.mock("@inertiajs/vue3", async importOriginal => ({ ...await importOriginal(), router: { get } }));
it("la consulta cargada es la base y solicitar otro rol conserva la captura hasta aceptar navegación", async () => {
    const form = useForm({ name: "", permissions: [] });
    const selected = { id: 1, name: "Consulta", permissions: [{ id: 7 }] };
    const other = { id: 2, name: "Otro", permissions: [] };
    const wrapper = shallowMount(RolePanel, { props: { selectedRole: selected, roles: [selected, other], modules: [], permissions: [], roleMembers: { data: [] }, formRolePermissions: form, capabilities: {}, teamId: 1 } });
    await flushPromises();
    expect(form.name).toBe("Consulta");
    expect(form.permissions).toEqual([7]);
    expect(form.isDirty).toBe(false);
    form.name = "Captura sin guardar";
    await flushPromises();
    wrapper.findComponent({ name: "RoleSidebar" }).vm.$emit("update:selectedRole", other);
    await flushPromises();
    expect(get).toHaveBeenCalledOnce();
    expect(form.name).toBe("Captura sin guardar");
    expect(form.isDirty).toBe(true);
    await wrapper.setProps({ selectedRole: other });
    await flushPromises();
    expect(form.name).toBe("Otro");
    expect(form.isDirty).toBe(false);
    wrapper.unmount();
});
