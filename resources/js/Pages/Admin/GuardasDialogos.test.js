import { flushPromises, shallowMount } from "@vue/test-utils";
import { afterEach, expect, it, vi } from "vitest";
import Teams from "./Teams/Index.vue";
import CreateRole from "./Roles/CreateRoleModal.vue";
import { forgetUnsavedChanges, hasUnsavedChanges } from "@/Utils/unsavedChanges";
vi.mock("@inertiajs/vue3", async importOriginal => ({ ...await importOriginal(), usePage: () => ({ props: { auth: { is_super_admin: true }, listado: null } }) }));
vi.mock("primevue/usetoast", () => ({ useToast: () => ({ add: vi.fn() }) }));
vi.mock("primevue/useconfirm", () => ({ useConfirm: () => ({ require: vi.fn() }) }));
const global = { renderStubDefaultSlot: true, stubs: { AppLayout: { template: '<main><slot name="card-content"/></main>' }, Dialog: { props: ["visible"], template: '<section v-if="visible"><slot/></section>' } } };
afterEach(() => { forgetUnsavedChanges(); vi.restoreAllMocks(); });
it("cancelar creación de equipo conserva al rechazar y limpia al aceptar", async () => {
    const wrapper = shallowMount(Teams, { props: { teams: [] }, global });
    wrapper.vm.openCreate();
    wrapper.vm.form.name = "Equipo sin guardar";
    await flushPromises();
    expect(hasUnsavedChanges()).toBe(true);
    const confirm = vi.spyOn(window, "confirm").mockReturnValue(false);
    wrapper.vm.closeCreate();
    expect(wrapper.vm.visible).toBe(true);
    expect(wrapper.vm.form.name).toBe("Equipo sin guardar");
    confirm.mockReturnValue(true);
    wrapper.vm.closeCreate();
    await flushPromises();
    expect(wrapper.vm.visible).toBe(false);
    expect(wrapper.vm.form.name).toBe("");
    expect(hasUnsavedChanges()).toBe(false);
    wrapper.unmount();
});
it("cancelar creación de rol elimina el borrador invisible del guardián", async () => {
    const wrapper = shallowMount(CreateRole, { props: { visible: true, teamId: 1 }, global });
    wrapper.vm.form.name = "Rol sin guardar";
    await flushPromises();
    vi.spyOn(window, "confirm").mockReturnValue(true);
    await wrapper.find('button-stub[label="Cancelar"]').trigger("click");
    await flushPromises();
    expect(wrapper.emitted("close")).toHaveLength(1);
    expect(wrapper.vm.form.name).toBe("");
    expect(hasUnsavedChanges()).toBe(false);
    wrapper.unmount();
});
